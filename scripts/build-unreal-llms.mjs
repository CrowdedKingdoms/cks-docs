#!/usr/bin/env node
// Concatenates every Unreal SDK page into static/helpers/unreal-sdk/llms-full.txt, one
// file an agent can read instead of crawling the site.
//
// Pages come out in sidebar order: root pages first by `sidebar_position`, then each
// folder by its `_category_.json` position, and inside a folder by `sidebar_position`
// then filename. Each page is written as `# <title>`, a `Source:` line with its public
// URL, and the body with front matter and import lines removed. A `<Blueprint src="x" />`
// becomes a pointer to the clipboard text it renders, since the graph itself is drawn
// in the browser. A `<CppSnippet id="x" />` becomes a fenced cpp block holding
// static/snippets/unreal-sdk/x.cpp, the same text the site inlines at build time.
//
// The site URL (prod) and the Unreal SDK route base are read from docusaurus.config.ts
// rather than repeated here, the same way check-content-policy.mjs derives its corpus.
// The output is committed and regenerated by `prebuild`; check-generated.mjs refuses a
// committed copy that differs from what this produces.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');

const DOCS = 'docs-unreal-sdk';
const OUT = 'static/helpers/unreal-sdk/llms-full.txt';
const SNIPPETS = 'static/snippets/unreal-sdk';

// --- site facts from the config ------------------------------------------------------

const config = readFileSync(resolve(repo, 'docusaurus.config.ts'), 'utf8');

const prodUrl = /prod:\s*\{\s*url:\s*'([^']+)'/.exec(config)?.[1];
if (!prodUrl) {
  console.error('[build-unreal-llms] COULD NOT RUN: no `prod: { url: ... }` in docusaurus.config.ts');
  process.exit(3);
}

const docsPlugin = new RegExp(`path:\\s*'${DOCS}',\\s*routeBasePath:\\s*'([^']+)'`).exec(config);
const routeBase = docsPlugin?.[1];
if (!routeBase) {
  console.error(`[build-unreal-llms] COULD NOT RUN: no docs plugin with path '${DOCS}' in docusaurus.config.ts`);
  process.exit(3);
}

// --- front matter ----------------------------------------------------------------------

function splitFrontMatter(text) {
  if (!text.startsWith('---')) return { meta: {}, body: text };
  const end = text.indexOf('\n---', 3);
  if (end < 0) return { meta: {}, body: text };
  const meta = {};
  for (const line of text.slice(4, end).split('\n')) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/.exec(line);
    if (!m) continue;
    meta[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return { meta, body: text.slice(end + 4).replace(/^\n+/, '') };
}

const position = (meta) => {
  const n = Number(meta.sidebar_position);
  return Number.isFinite(n) ? n : Number.MAX_SAFE_INTEGER;
};

// --- ordering ----------------------------------------------------------------------------

function categoryPosition(dir) {
  const file = join(dir, '_category_.json');
  if (!existsSync(file)) return Number.MAX_SAFE_INTEGER;
  const n = Number(JSON.parse(readFileSync(file, 'utf8')).position);
  return Number.isFinite(n) ? n : Number.MAX_SAFE_INTEGER;
}

function readPage(file, docsRoot) {
  const raw = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  const { meta, body } = splitFrontMatter(raw);
  const rel = relative(docsRoot, file).replace(/\\/g, '/');
  const id = rel.replace(/\.mdx?$/, '');
  const dir = id.includes('/') ? id.slice(0, id.lastIndexOf('/') + 1) : '';
  let slug = meta.slug;
  if (!slug) slug = id;
  else if (slug.startsWith('/')) slug = slug.slice(1);
  else slug = dir + slug;
  const title = meta.title || (/^#\s+(.+)$/m.exec(body)?.[1] ?? basename(id));
  return { file, rel, position: position(meta), title, url: `${prodUrl}${routeBase}/${slug}`, body };
}

// Root pages first, then folders by category position; recursion keeps the same rule.
function collect(dir, docsRoot) {
  const names = readdirSync(dir).sort();
  const pages = [];
  const folders = [];
  for (const name of names) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) folders.push(full);
    else if (/\.mdx?$/.test(name) && !name.startsWith('_')) pages.push(readPage(full, docsRoot));
  }
  pages.sort((a, b) => a.position - b.position || a.rel.localeCompare(b.rel));
  folders.sort((a, b) => categoryPosition(a) - categoryPosition(b) || a.localeCompare(b));
  return pages.concat(...folders.map((f) => collect(f, docsRoot)));
}

// --- body rewriting ----------------------------------------------------------------------

function cppSnippet(id) {
  const file = resolve(repo, SNIPPETS, `${id}.cpp`);
  if (!existsSync(file)) return `[Missing C++ snippet: ${id}]`;
  const code = readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trimEnd();
  return '```cpp\n' + code + '\n```';
}

function rewrite(body) {
  return body
    .split('\n')
    .filter((line) => !/^import\s.*from\s+['"][^'"]+['"];?\s*$/.test(line) && !/^import\s+['"][^'"]+['"];?\s*$/.test(line))
    .map((line) =>
      line
        .replace(/<Blueprint\b[^>]*\bsrc=["']([^"']+)["'][^>]*\/>/g, (_, src) =>
          `[Blueprint snippet: ${src}, see /bp/unreal-sdk/${src}.txt]`,
        )
        .replace(/<CppSnippet\b[^>]*\bid=["']([^"']+)["'][^>]*\/>/g, (_, id) => cppSnippet(id)),
    )
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

// --- write -------------------------------------------------------------------------------

const docsRoot = resolve(repo, DOCS);
const pages = collect(docsRoot, docsRoot);

const chunks = pages.map((p) => `# ${p.title}\nSource: ${p.url}\n\n${rewrite(p.body)}\n`);
const out = chunks.join('\n');

const outPath = resolve(repo, OUT);
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out);
console.log(`[build-unreal-llms] ${OUT}: ${pages.length} page(s), ${out.length} chars`);
