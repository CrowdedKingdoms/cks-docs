#!/usr/bin/env node
// Writes vendor/klee/plugins/crowdy-names.generated.ts from static/helpers/unreal-sdk/sdk-surface.json:
// the Blueprint display name of every SDK function, keyed by its C++ name. The Blueprint renderer
// titles a call node from the member name in the clipboard text, which never carries a
// DisplayName, so without this table `GetFloat` would render as "Get Float" where the editor
// shows "Get Model Attribute (Float)". Runs in prebuild; the output is committed like the SDL.

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const surfacePath = path.join(root, 'static/helpers/unreal-sdk/sdk-surface.json');
const outPath = path.join(root, 'vendor/klee/plugins/crowdy-names.generated.ts');

if (!fs.existsSync(surfacePath)) {
  console.error(`[build-klee-names] missing ${path.relative(root, surfacePath)}; run Export-SdkSurface.ps1 in crowdy-sdk and copy it here`);
  process.exit(2);
}
const surface = JSON.parse(fs.readFileSync(surfacePath, 'utf8'));

// Two tables: by "Class::Name" with the U/A prefix dropped, the way the clipboard text names the
// owning class, and by bare member name as the fallback. A subsystem method and its async factory
// often share a name with different display names (GetChannels / "Get All Channels"), which is what
// the qualified table settles; the bare table keeps the first and reports the rest.
const byClass = new Map();
const byName = new Map();
const conflicts = [];
for (const fn of [...surface.functions].sort((a, b) => a.id.localeCompare(b.id))) {
  if (!fn.display_name || fn.display_name === fn.name) continue;
  byClass.set(`${fn.class.replace(/^[UA]/, '')}::${fn.name}`, fn.display_name);
  const existing = byName.get(fn.name);
  if (existing && existing !== fn.display_name) {
    conflicts.push(`${fn.name}: "${existing}" vs "${fn.display_name}" (${fn.class}), settled by the qualified table`);
    continue;
  }
  byName.set(fn.name, fn.display_name);
}

const entries = (map) => [...map.entries()].map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const lines = [
  '// Generated by scripts/build-klee-names.mjs from static/helpers/unreal-sdk/sdk-surface.json. Do not edit.',
  `// SDK ${surface.sdk_version}: ${byClass.size} qualified names, ${byName.size} bare names.`,
  'export const CrowdyFunctionNamesByClass: {[classAndMember: string]: string} = {',
  ...entries(byClass),
  '};',
  '',
  'export const CrowdyFunctionNames: {[memberName: string]: string} = {',
  ...entries(byName),
  '};',
  '',
];
const names = byClass;
fs.mkdirSync(path.dirname(outPath), {recursive: true});
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`[build-klee-names] ${path.relative(root, outPath)}: ${names.size} names from SDK ${surface.sdk_version}`);
for (const c of conflicts) console.warn(`[build-klee-names] conflicting display names, first kept: ${c}`);
