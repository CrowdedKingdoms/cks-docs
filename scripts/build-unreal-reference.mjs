#!/usr/bin/env node
// Writes the Unreal SDK reference tables, one small JSON file per table under
// src/generated/unreal-sdk/, from static/helpers/unreal-sdk/sdk-surface.json. A reference
// page renders one with <SurfaceTable table="..."/> (src/components/SurfaceTable.tsx) so the
// 2.6 MB manifest is never imported by a page.
//
// Each table file is {generated_from, sdk_version, table, columns, rows}. `columns` names
// and types the row keys the component renders; every row also carries `id`, the same id
// check-unreal-surface.mjs judges coverage by, which is what a page's `notes` prop keys on.
//
// The `page` column is where a reader goes to read more. It is computed the way
// check-unreal-surface.mjs computes coverage (the same corpus, the same whole-word test on
// the same term per group), except that the list of matching pages is kept and one is
// picked: the page mentioning the symbol most often, ties broken by folder (concepts,
// runtime, game-models, services, studio, guides, then the root pages) and path. Pages
// under reference/ never count, since a symbol appearing in its own table is not further
// reading. No match leaves the cell empty; symbol-pages.json holds the whole id-to-slug map.
// PAGE_OVERRIDES pins an id to a page where the count picks a passing mention (a page whose
// only mention is a warning that the symbol is not what the page is about).
//
// Rows from a private header (`public_header: false`) are dropped. Rows from an editor
// module stay in the file with `editor: true`, and rows the allowlist
// (scripts/unreal-surface-allowlist.json) names carry their reason in `allowlist`; the
// component hides both kinds unless a page asks for them. The editor modules are the ones
// the manifest itself marks `editor_module` anywhere.
//
// Output is committed and regenerated by `prebuild`; check-generated.mjs refuses a
// committed copy that differs from what this produces. Sorted throughout, so two runs on
// the same manifest and pages are byte-identical.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '..');

const SURFACE = 'static/helpers/unreal-sdk/sdk-surface.json';
const ALLOWLIST = 'scripts/unreal-surface-allowlist.json';
const DOCS = 'docs-unreal-sdk';
const OUT_DIR = 'src/generated/unreal-sdk';
const FOLDER_ORDER = ['concepts', 'runtime', 'game-models', 'services', 'studio', 'guides', ''];
const MODULE_ORDER = ['CrowdySDK', 'CrowdyNet', 'CrowdyReplication', 'CrowdyServices', 'CrowdyVoice'];
// id -> page id under docs-unreal-sdk/, where the mention count would send a reader to a
// page that only says the symbol is not covered there.
const PAGE_OVERRIDES = {
  UCrowdyGameSession: 'services/authentication',
};

// --- inputs --------------------------------------------------------------------------

const surfacePath = resolve(repo, SURFACE);
if (!existsSync(surfacePath)) {
  console.error(
    `[build-unreal-reference] COULD NOT RUN: ${SURFACE} is missing.\n` +
      `  It is generated in the crowdy-sdk repository by scripts/Export-SdkSurface.ps1 and copied here.`,
  );
  process.exit(3);
}
const surface = JSON.parse(readFileSync(surfacePath, 'utf8'));

const config = readFileSync(resolve(repo, 'docusaurus.config.ts'), 'utf8');
const routeBase = new RegExp(`path:\\s*'${DOCS}',\\s*routeBasePath:\\s*'([^']+)'`).exec(config)?.[1];
if (!routeBase) {
  console.error(`[build-unreal-reference] COULD NOT RUN: no docs plugin with path '${DOCS}' in docusaurus.config.ts`);
  process.exit(3);
}

const allowlistPath = resolve(repo, ALLOWLIST);
const allowlist = new Map();
for (const entry of existsSync(allowlistPath) ? JSON.parse(readFileSync(allowlistPath, 'utf8')) : []) {
  if (entry && typeof entry.id === 'string') allowlist.set(entry.id, entry.reason);
}
const allowlistReason = (id, owner) => allowlist.get(id) ?? (owner ? allowlist.get(owner) : undefined) ?? '';

const editorModules = new Set();
for (const list of Object.values(surface)) {
  if (!Array.isArray(list)) continue;
  for (const e of list) if (e.editor_module === true) editorModules.add(e.module);
}
const isEditor = (e) => e.editor_module === true || editorModules.has(e.module);

// --- corpus (same walk, front-matter strip and whole-word test as check-unreal-surface.mjs) ---

function walk(dir, out = []) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.mdx?$/.test(name) && !name.startsWith('_')) out.push(full);
  }
  return out;
}

function splitFrontMatter(text) {
  if (!text.startsWith('---')) return { meta: {}, body: text };
  const end = text.indexOf('\n---', 3);
  if (end < 0) return { meta: {}, body: text };
  const meta = {};
  for (const line of text.slice(4, end).split('\n')) {
    const m = /^([A-Za-z_][A-Za-z0-9_]*):\s*(.*)$/.exec(line);
    if (m) meta[m[1]] = m[2].trim().replace(/^(['"])(.*)\1$/, '$2');
  }
  return { meta, body: text.slice(end + 4) };
}

const docsRoot = resolve(repo, DOCS);
const pages = walk(docsRoot)
  .map((file) => {
    const { meta, body } = splitFrontMatter(readFileSync(file, 'utf8').replace(/\r\n/g, '\n'));
    const id = relative(docsRoot, file).replace(/\\/g, '/').replace(/\.mdx?$/, '');
    const folder = id.includes('/') ? id.slice(0, id.indexOf('/')) : '';
    const dir = id.includes('/') ? id.slice(0, id.lastIndexOf('/') + 1) : '';
    let slug = meta.slug || id;
    if (slug.startsWith('/')) slug = slug.slice(1);
    else if (meta.slug) slug = dir + slug;
    return { id, folder, slug, text: body, rank: FOLDER_ORDER.indexOf(folder) };
  })
  .filter((p) => p.rank >= 0)
  .sort((a, b) => a.rank - b.rank || a.id.localeCompare(b.id));

const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const wordRe = (term) => new RegExp(`(?<![A-Za-z0-9_])${escape(term)}(?![A-Za-z0-9_])`);
const pagesMentioning = (term) => {
  const re = wordRe(term);
  return pages.filter((p) => re.test(p.text));
};

// The slug of the page that mentions the terms most often (the page explaining a symbol
// repeats it; a page mentioning it in passing does so once), ties broken by folder order
// then path. A page that also mentions `owner` wins outright, so `OnCompleted` on the
// owning class's page beats the same name on an unrelated one.
function pageFor(terms, owner) {
  const ownerRe = owner ? wordRe(owner) : null;
  const hits = new Map();
  for (const t of terms) {
    if (!t) continue;
    const re = new RegExp(wordRe(t).source, 'g');
    for (const p of pagesMentioning(t)) {
      const hit = hits.get(p) ?? { page: p, count: 0, owner: ownerRe ? ownerRe.test(p.text) : false };
      hit.count += p.text.match(re).length;
      hits.set(p, hit);
    }
  }
  if (!hits.size) return '';
  const best = [...hits.values()].sort(
    (a, b) => Number(b.owner) - Number(a.owner) || b.count - a.count || a.page.rank - b.page.rank || a.page.id.localeCompare(b.page.id),
  )[0];
  return best.page.slug;
}

// --- ordering helpers ------------------------------------------------------------------

const moduleRank = (m) => {
  const i = MODULE_ORDER.indexOf(m);
  return i < 0 ? MODULE_ORDER.length : i;
};
const byModuleThen = (key) => (a, b) =>
  moduleRank(a.module) - moduleRank(b.module) || a.module.localeCompare(b.module) || a[key].localeCompare(b[key]);
const shortHeader = (h) => h.split('/').pop();
const isPublic = (e) => e.public_header !== false;

// --- tables -------------------------------------------------------------------------------

const pageById = new Map(pages.map((p) => [p.id, p]));
for (const [id, pageId] of Object.entries(PAGE_OVERRIDES)) {
  if (pageById.has(pageId)) continue;
  console.error(`[build-unreal-reference] COULD NOT RUN: PAGE_OVERRIDES['${id}'] names a page that does not exist: ${DOCS}/${pageId}.md`);
  process.exit(3);
}

const symbolPages = {};
const note = (id, computed) => {
  const slug = id in PAGE_OVERRIDES ? pageById.get(PAGE_OVERRIDES[id]).slug : computed;
  if (slug) symbolPages[id] = slug;
  return slug;
};

const tables = {};
const excluded = {};
const editorCount = {};
const allowlistCount = {};

function table(name, columns, rows, dropped) {
  for (const r of rows) r.allowlist = allowlistReason(r.id, r.class);
  tables[name] = { columns, rows };
  excluded[name] = dropped;
  editorCount[name] = rows.filter((r) => r.editor).length;
  allowlistCount[name] = rows.filter((r) => r.allowlist).length;
}

{
  const src = surface.subsystems;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      class: e.id,
      base: e.base,
      outer: e.outer,
      module: e.module,
      page: note(e.id, pageFor([e.id])),
      editor: isEditor(e),
    }))
    .sort(byModuleThen('class'));
  table(
    'subsystems',
    [
      { key: 'class', label: 'Class', kind: 'code' },
      { key: 'base', label: 'Base', kind: 'code' },
      { key: 'outer', label: 'Outer', kind: 'text' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.async_actions;
  // The palette title is the factory function's DisplayName, carried by the matching
  // `functions` entry; the factory's own name is what C++ calls.
  const displayName = new Map(surface.functions.map((f) => [f.id, f.display_name]));
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      node: e.factories.map((f) => displayName.get(`${e.id}::${f}`) || f),
      factories: e.factories,
      class: e.id,
      pins: e.pins,
      module: e.module,
      page: note(e.id, pageFor([e.id])),
      editor: isEditor(e),
    }))
    .sort(byModuleThen('class'));
  table(
    'async-actions',
    [
      { key: 'node', label: 'Blueprint node', kind: 'text' },
      { key: 'factories', label: 'C++ factory', kind: 'list' },
      { key: 'class', label: 'Class', kind: 'code' },
      { key: 'pins', label: 'Completion pins', kind: 'list' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.delegates;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      owner: e.class,
      name: e.name,
      type: e.type,
      category: e.category,
      module: e.module,
      page: note(e.id, pageFor([e.name], e.class)),
      editor: isEditor(e),
    }))
    .sort((a, b) => byModuleThen('owner')(a, b) || a.name.localeCompare(b.name));
  table(
    'delegates',
    [
      { key: 'owner', label: 'Owner', kind: 'code' },
      { key: 'name', label: 'Delegate', kind: 'code' },
      { key: 'type', label: 'Signature type', kind: 'code' },
      { key: 'category', label: 'Category', kind: 'text' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

const ROLE_ORDER = ['trace', 'behaviour', 'command'];
const cvarRole = (e) => (e.kind === 'command' ? 'command' : e.trace ? 'trace' : 'behaviour');
// The exporter reads a command's help up to the next string literal, so a `[Crowdy...]` log
// line or a printf token that follows it in the same lambda is captured too; cut there.
const cleanHelp = (help) => help.replace(/\[Crowdy[\s\S]*$/, '').replace(/%[-+ 0#]*\d*(?:\.\d+)?(?:ll|l|h)?[a-zA-Z][\s\S]*$/, '').trim();
{
  const src = surface.cvars;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      name: e.id,
      kind: e.kind,
      role: cvarRole(e),
      trace: e.trace === true,
      help: cleanHelp(e.help ?? ''),
      module: e.module,
      editor: isEditor(e),
    }))
    .sort((a, b) => ROLE_ORDER.indexOf(a.role) - ROLE_ORDER.indexOf(b.role) || a.name.localeCompare(b.name));
  table(
    'cvars',
    [
      { key: 'name', label: 'Name', kind: 'code' },
      { key: 'kind', label: 'Kind', kind: 'text' },
      { key: 'role', label: 'Role', kind: 'text' },
      { key: 'trace', label: 'Trace gate', kind: 'flag' },
      { key: 'help', label: 'Help', kind: 'text' },
      { key: 'module', label: 'Module', kind: 'text' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.settings;
  const rows = [];
  let dropped = 0;
  for (const s of [...src].sort((a, b) => a.id.localeCompare(b.id))) {
    if (!isPublic(s)) {
      dropped += (s.properties ?? []).length;
      continue;
    }
    for (const p of s.properties ?? []) {
      rows.push({
        id: `${s.id}::${p.name}`,
        class: s.id,
        property: p.name,
        type: p.type,
        category: p.category,
        config: p.config === true,
        written_by: p.edit === false ? 'Config Sync' : 'you',
        module: s.module,
        editor: isEditor(s),
      });
    }
  }
  table(
    'settings',
    [
      { key: 'class', label: 'Class', kind: 'code' },
      { key: 'property', label: 'Property', kind: 'code' },
      { key: 'type', label: 'Type', kind: 'code' },
      { key: 'category', label: 'Category', kind: 'text' },
      { key: 'config', label: 'Saved to config', kind: 'flag' },
      { key: 'written_by', label: 'Written by', kind: 'text' },
      { key: 'module', label: 'Module', kind: 'text' },
    ],
    rows,
    dropped,
  );
}

{
  const src = surface.meta_keys;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      key: e.id,
      owner: e.symbol.includes('::') ? e.symbol.slice(0, e.symbol.indexOf('::')) : '',
      symbol: e.symbol,
      header: shortHeader(e.header),
      module: e.module,
      page: note(e.id, pageFor([e.id])),
      editor: isEditor(e),
    }))
    .sort((a, b) => a.owner.localeCompare(b.owner) || a.key.localeCompare(b.key));
  table(
    'meta-keys',
    [
      { key: 'key', label: 'Key', kind: 'code' },
      { key: 'owner', label: 'Namespace', kind: 'code' },
      { key: 'symbol', label: 'Symbol', kind: 'code' },
      { key: 'header', label: 'Header', kind: 'code' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.enums;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      name: e.id,
      values: e.values,
      module: e.module,
      header: shortHeader(e.header),
      page: note(e.id, pageFor([e.id])),
      editor: isEditor(e),
    }))
    .sort(byModuleThen('name'));
  table(
    'enums',
    [
      { key: 'name', label: 'Enum', kind: 'code' },
      { key: 'values', label: 'Values', kind: 'list' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'header', label: 'Header', kind: 'code' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.log_categories;
  const categoriesIn = (module) => src.filter((c) => c.module === module);
  // A trace CVar `crowdy.<area>.trace` pairs with its module's only category, or with the
  // category whose name ends in the area (crowdy.rpc.trace -> LogCrowdyRPC), or failing
  // that with the category named after the module itself (crowdy.entity.trace ->
  // LogCrowdyReplication). A `.scopes` CVar emits Insights CPU scopes, not log lines.
  const moduleCategory = (module) => `Log${module}`;
  const areaOf = (v) => (v.id.split('.')[1] ?? '').toLowerCase();
  const namedCategoryFor = (v) => categoriesIn(v.module).find((c) => c.id.toLowerCase().endsWith(areaOf(v)));
  const categoryFor = (v) => {
    const own = categoriesIn(v.module);
    if (own.length === 1) return own[0].id;
    return namedCategoryFor(v)?.id ?? own.find((c) => c.id === moduleCategory(v.module))?.id ?? '';
  };
  const traceCvarsFor = (c) =>
    surface.cvars
      .filter((v) => v.trace === true && v.module === c.module && !v.id.endsWith('.scopes'))
      .filter((v) => categoryFor(v) === c.id)
      .map((v) => v.id)
      .sort();
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      category: e.id,
      module: e.module,
      trace_cvars: traceCvarsFor(e),
      editor: isEditor(e),
    }))
    .sort(byModuleThen('category'));
  table(
    'log-categories',
    [
      { key: 'category', label: 'Category', kind: 'code' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'trace_cvars', label: 'Trace CVar', kind: 'list' },
    ],
    rows,
    src.length - rows.length,
  );
}

{
  const src = surface.structs;
  const rows = src
    .filter(isPublic)
    .map((e) => ({
      id: e.id,
      name: e.id,
      display_name: e.meta?.DisplayName ?? '',
      module: e.module,
      header: shortHeader(e.header),
      page: note(e.id, pageFor([e.id])),
      editor: isEditor(e),
    }))
    .sort(byModuleThen('name'));
  table(
    'structs',
    [
      { key: 'name', label: 'Struct', kind: 'code' },
      { key: 'display_name', label: 'Display name', kind: 'text' },
      { key: 'module', label: 'Module', kind: 'text' },
      { key: 'header', label: 'Header', kind: 'code' },
      { key: 'page', label: 'Read more', kind: 'page' },
    ],
    rows,
    src.length - rows.length,
  );
}

// --- write ----------------------------------------------------------------------------------

const outDir = resolve(repo, OUT_DIR);
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const stamp = { generated_from: surface.generated, sdk_version: surface.sdk_version };
const write = (name, body) => writeFileSync(join(outDir, `${name}.json`), JSON.stringify(body, null, 2) + '\n');

for (const [name, { columns, rows }] of Object.entries(tables)) {
  write(name, { ...stamp, table: name, columns, rows });
}
const sortedPages = Object.fromEntries(Object.entries(symbolPages).sort(([a], [b]) => a.localeCompare(b)));
write('symbol-pages', { ...stamp, route_base: routeBase, pages: sortedPages });

console.log(`[build-unreal-reference] ${OUT_DIR}/: SDK ${surface.sdk_version}, ${pages.length} page(s) scanned for links`);
for (const [name, { rows }] of Object.entries(tables)) {
  const linked = rows.filter((r) => r.page).length;
  const parts = [`${rows.length} rows`];
  if ('page' in (rows[0] ?? {})) parts.push(`${linked} linked`);
  if (editorCount[name]) parts.push(`${editorCount[name]} editor (hidden by default)`);
  if (allowlistCount[name]) parts.push(`${allowlistCount[name]} allowlisted (hidden by default)`);
  if (excluded[name]) parts.push(`${excluded[name]} private dropped`);
  console.log(`  ${name.padEnd(16)} ${parts.join(', ')}`);
}
